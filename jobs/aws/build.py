"""Build jobs/aws/kvevac-aws.sh, the one-file AWS CloudShell runner.

The runner is jobs/aws/driver.sh with these files embedded:
- the instance user-data (gzipped, under EC2's 16 KB limit): jobs/aws/instance_job.sh,
  the notice logger, and the kvevac modules the measurements import;
- console_channel.py and notice_timing.py, which the runner itself uses in CloudShell;
- the FIS role trust policy and experiment template from jobs/aws_fis/.

    python jobs/aws/build.py           # rewrite kvevac-aws.sh
    python jobs/aws/build.py --check   # exit 1 if kvevac-aws.sh is out of date
"""

from __future__ import annotations

import argparse
import base64
import gzip
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "jobs" / "aws"
OUTPUT = HERE / "kvevac-aws.sh"
USER_DATA_LIMIT = 16_384  # bytes, EC2's limit on raw user-data
DELIMITER = "KVEVAC_EOF"

# Instance path (under $ROOT on the instance) -> repository path.
INSTANCE_FILES = {
    "src/kvevac/__init__.py": "kvevac/__init__.py",
    "src/kvevac/profiles.py": "kvevac/profiles.py",
    "src/kvevac/calibration.py": "kvevac/calibration.py",
    "src/kvevac/measure/__init__.py": "kvevac/measure/__init__.py",
    "src/kvevac/measure/prefill.py": "kvevac/measure/prefill.py",
    "src/kvevac/measure/interference.py": "kvevac/measure/interference.py",
    "src/kvevac/measure/ingest_load.py": "kvevac/measure/ingest_load.py",
    "src/kvevac/measure/console_channel.py": "kvevac/measure/console_channel.py",
    "notice_logger.py": "jobs/aws_fis/notice_logger.py",
    "job.sh": "jobs/aws/instance_job.sh",
}


def user_data() -> str:
    parts = [
        "#!/bin/bash",
        "# kvevac Phase 2 instance user-data. Generated by jobs/aws/build.py; do not edit.",
        'ROOT="${KVEVAC_ROOT:-/opt/kvevac}"',
        'mkdir -p "$ROOT/src/kvevac/measure"',
    ]
    for target, source in INSTANCE_FILES.items():
        text = (ROOT / source).read_text()
        if DELIMITER in text:
            raise SystemExit(f"{source} contains the heredoc delimiter {DELIMITER}")
        parts += [f"cat > \"$ROOT/{target}\" <<'{DELIMITER}'", text.rstrip("\n"), DELIMITER]
    parts.append('exec bash "$ROOT/job.sh"')
    return "\n".join(parts) + "\n"


def _gzip(data: bytes) -> bytes:
    """Reproducible gzip: Python 3.14 writes the host OS into the header (byte 9), where
    earlier versions wrote 255 ("unknown"). Pin it so the build is host-independent."""
    packed = bytearray(gzip.compress(data, compresslevel=9, mtime=0))
    packed[9] = 255
    return bytes(packed)


def _gz_b64(text: str) -> str:
    packed = _gzip(text.encode())
    return "\n".join(textwrap.wrap(base64.b64encode(packed).decode(), 76))


def build() -> tuple[str, int]:
    data = user_data()
    size = len(_gzip(data.encode()))
    # The runner prepends a few `export` lines, so leave headroom.
    if size > USER_DATA_LIMIT - 1024:
        raise SystemExit(f"gzipped user-data is {size} bytes; EC2 allows {USER_DATA_LIMIT}")
    replacements = {
        "@USERDATA_GZ_B64@": _gz_b64(data),
        "@CONSOLE_CHANNEL_GZ_B64@": _gz_b64(
            (ROOT / "kvevac/measure/console_channel.py").read_text()),
        "@NOTICE_TIMING_GZ_B64@": _gz_b64(
            (ROOT / "kvevac/measure/notice_timing.py").read_text()),
        "@FIS_TRUST_JSON@": (ROOT / "jobs/aws_fis/fis-trust.json").read_text().rstrip("\n"),
        "@FIS_TEMPLATE_JSON@": (ROOT / "jobs/aws_fis/fis-template.json").read_text().rstrip("\n"),
    }
    script = (HERE / "driver.sh").read_text()
    for key, value in replacements.items():
        if key not in script:
            raise SystemExit(f"driver.sh has no {key} placeholder")
        script = script.replace(key, value)
    return script, size


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="fail if kvevac-aws.sh differs from a fresh build")
    args = parser.parse_args()
    script, size = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != script:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run python jobs/aws/build.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0
    OUTPUT.write_text(script)
    OUTPUT.chmod(0o755)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(script)} bytes; "
          f"user-data {size} bytes gzipped, limit {USER_DATA_LIMIT})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
